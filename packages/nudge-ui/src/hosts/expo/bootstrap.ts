import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DOCUMENT_HEAD_SCRIPT } from "../../inspector/canvas/documentHeadScript.ts";
import {
  NUDGE_UI_CLIENT_PATH,
  NUDGE_UI_EDITOR_PATH,
  NUDGE_UI_EDITOR_QUERY_PARAM,
  NUDGE_UI_EDITOR_QUERY_VALUE,
  NUDGE_UI_MANIFEST_PATH,
} from "../../transport/index.ts";
import { REACT_RENDERER_CAPTURE_SCRIPT } from "../reactRendererCapture.ts";

/** Generated beside other Nudge state; it ignores itself so it never reaches git. */
export interface ExpoBootstrapPaths {
  readonly directory: string;
  readonly bootstrap: string;
}

export function expoBootstrapPaths(root: string): ExpoBootstrapPaths {
  const directory = join(root, ".nudge", "expo");
  return { directory, bootstrap: join(directory, "bootstrap.js") };
}

/**
 * Expo serves the web document from its own middleware, ahead of anything a Metro config can add, so the bootstrap
 * travels in the bundle instead: a polyfill, which Metro runs before any module and therefore before React DOM loads.
 * It does what the other hosts' `<head>` scripts do, and adds the client the way their `<body>` tags do.
 */
export function createExpoBootstrapScript(): string {
  return `/* Generated by nudge-ui for Expo web development. */
(function () {
  if (typeof window === "undefined" || typeof document === "undefined" || !document.documentElement) return;
  if (document.documentElement.hasAttribute("data-nudge-ui-editor")) return;
  try {
    var url = new URL(window.location.href);
    if (url.searchParams.getAll(${JSON.stringify(NUDGE_UI_EDITOR_QUERY_PARAM)}).indexOf(${JSON.stringify(NUDGE_UI_EDITOR_QUERY_VALUE)}) !== -1) {
      // Expo answered an editor request with the app's own document (its root route is served before Metro's
      // middleware), so hand over to the editor route, which names the page in its query.
      var kept = new URLSearchParams();
      url.searchParams.forEach(function (value, key) {
        if (key !== ${JSON.stringify(NUDGE_UI_EDITOR_QUERY_PARAM)} || value !== ${JSON.stringify(NUDGE_UI_EDITOR_QUERY_VALUE)}) kept.append(key, value);
      });
      url.search = kept.toString();
      window.location.replace(${JSON.stringify(`${NUDGE_UI_EDITOR_PATH}?url=`)} + encodeURIComponent(url.pathname + url.search + url.hash));
      return;
    }
  } catch (error) {
    /* an unparsable address leaves the page as it is */
  }
${REACT_RENDERER_CAPTURE_SCRIPT}
${DOCUMENT_HEAD_SCRIPT}
  if (document.querySelector("script[data-nudge-ui-client]")) return;
  var script = document.createElement("script");
  script.type = "module";
  script.src = ${JSON.stringify(NUDGE_UI_CLIENT_PATH)};
  script.setAttribute("data-nudge-ui-client", "");
  script.setAttribute("data-nudge-ui-manifest", ${JSON.stringify(NUDGE_UI_MANIFEST_PATH)});
  script.addEventListener("error", function () {
    console.warn("[nudge-ui] inspector bootstrap failed to load.");
  });
  (document.head || document.documentElement).appendChild(script);
})();
`;
}

/** Writes the bootstrap only when its text changed, so Metro does not see a fresh file on every config evaluation. */
export function writeExpoBootstrap(root: string): string {
  const paths = expoBootstrapPaths(root);
  mkdirSync(paths.directory, { recursive: true });
  writeIfChanged(join(paths.directory, ".gitignore"), "*\n");
  writeIfChanged(paths.bootstrap, createExpoBootstrapScript());
  return paths.bootstrap;
}

function writeIfChanged(path: string, contents: string): void {
  try {
    if (readFileSync(path, "utf8") === contents) return;
  } catch {
    /* absent: written below */
  }
  writeFileSync(path, contents);
}

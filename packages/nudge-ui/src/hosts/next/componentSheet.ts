import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, resolve, sep } from "node:path";
import type { ComponentContract } from "../../compiler/index.ts";
import type { ComponentFrameworkAdapter } from "../componentFramework/adapter.ts";
import { findSheetWrapperFile, serializeSheetDefinition, suggestedSheetWrapperFile } from "../componentFramework/sheet.ts";

/**
 * Component sheets on Next.js (ADR-0050). Next routes only files under `app/`, so the route is a stub there
 * that ignores itself in git and is routable only while `next dev` registers {@link NEXT_SHEET_PAGE_EXTENSION}.
 * Everything that changes with the project lives in `.nudge/next/`.
 */

/** `%5F` escapes the underscore that would otherwise make the folder private; the route is `/__nudge_ui__/components`. */
export const NEXT_SHEET_ROUTE_FOLDER = "%5F%5Fnudge_ui%5F%5F";
/**
 * Registered only in development; `next build` reads `page.nudge.jsx` as `page.nudge` with extension `jsx`, which is no
 * route. JavaScript, not TypeScript: a `.tsx` file under `app/` makes Next demand TypeScript in a JavaScript project.
 */
export const NEXT_SHEET_PAGE_EXTENSION = "nudge.jsx";
/** The stub's earlier name, still removed on cleanup. */
const LEGACY_SHEET_PAGE_NAME = "page.nudge.tsx";
export const NEXT_SHEET_RUNTIME_MODULE = "nudge-ui/internal/next/component-sheet";
const STUB_MARKER = "Generated by Nudge UI";
const NEXT_DEFAULT_PAGE_EXTENSIONS = ["tsx", "ts", "jsx", "js"] as const;

export interface NextSheetPaths {
  root: string;
  /** The App Router directory the stub route lives in. */
  appDirectory: string;
  /** `<appDirectory>/%5F%5Fnudge_ui%5F%5F`, removed whole when the sheet is cleaned up. */
  routeFolder: string;
  page: string;
  /** The generated module the page imports its contracts and loaders from. */
  definition: string;
}

const ROOT_LAYOUTS = ["layout.tsx", "layout.jsx", "layout.ts", "layout.js"];

function hasRootLayout(directory: string): boolean {
  try {
    return statSync(directory).isDirectory() && ROOT_LAYOUTS.some((name) => existsSync(join(directory, name)));
  } catch {
    return false;
  }
}

/** Null when the project has no App Router root layout to render the sheet inside: Pages Router and per-group root layouts. */
export function nextSheetPaths(root: string): NextSheetPaths | null {
  const appDirectory = [join(root, "app"), join(root, "src", "app")].find(hasRootLayout);
  if (!appDirectory) return null;
  const routeFolder = join(appDirectory, NEXT_SHEET_ROUTE_FOLDER);
  return {
    root,
    appDirectory,
    routeFolder,
    page: join(routeFolder, "components", `page.${NEXT_SHEET_PAGE_EXTENSION}`),
    definition: join(root, ".nudge", "next", "component-sheet.ts"),
  };
}

/** Next's own default unless the project set its own list. */
export function withSheetPageExtension(pageExtensions: unknown): string[] {
  const current = Array.isArray(pageExtensions) && pageExtensions.every((entry) => typeof entry === "string")
    ? pageExtensions as string[]
    : [...NEXT_DEFAULT_PAGE_EXTENSIONS];
  return current.includes(NEXT_SHEET_PAGE_EXTENSION) ? current : [...current, NEXT_SHEET_PAGE_EXTENSION];
}

/** A specifier Turbopack and webpack both resolve from `from`'s directory. */
function relativeSpecifier(from: string, to: string): string {
  const path = relative(dirname(from), to).split(sep).join(posix.sep);
  return path.startsWith(".") ? path : `./${path}`;
}

/** Written without JSX, so the identity loader leaves it alone. */
export function createSheetPageSource(paths: NextSheetPaths): string {
  return [
    `// ${STUB_MARKER} for \`next dev\`. It is routed only while Nudge UI registers the \`${NEXT_SHEET_PAGE_EXTENSION}\` page extension,`,
    "// and the .gitignore beside it keeps the folder out of git. Safe to delete.",
    "// @ts-nocheck",
    '"use client";',
    'import { createElement } from "react";',
    `import { NextComponentSheet } from ${JSON.stringify(NEXT_SHEET_RUNTIME_MODULE)};`,
    `import { componentSheet } from ${JSON.stringify(relativeSpecifier(paths.page, paths.definition.replace(/\.ts$/, "")))};`,
    "",
    "export default function NudgeUiComponentSheetPage() {",
    "  return createElement(NextComponentSheet, componentSheet);",
    "}",
    "",
  ].join("\n");
}

function writeIfChanged(file: string, content: string): boolean {
  try {
    if (readFileSync(file, "utf8") === content) return false;
  } catch {
    // absent: written below
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return true;
}

/** Writes the stub route, and an empty definition when none exists yet, so the first compile never misses a module. */
export function writeSheetRoute(paths: NextSheetPaths, framework: ComponentFrameworkAdapter): void {
  // A stub under the earlier `.tsx` name would still make a JavaScript project look like TypeScript to Next.
  const legacyPage = join(dirname(paths.page), LEGACY_SHEET_PAGE_NAME);
  if (isGeneratedStub(legacyPage)) rmSync(legacyPage, { force: true });
  writeIfChanged(join(paths.routeFolder, ".gitignore"), "*\n");
  writeIfChanged(paths.page, createSheetPageSource(paths));
  if (!existsSync(paths.definition)) {
    writeIfChanged(paths.definition, serializeNextSheetDefinition({
      framework,
      root: paths.root,
      definition: paths.definition,
      contracts: [],
    }));
  }
}

/** Removes a stub this package wrote, so production type checks and builds never see it; anything else is left alone. */
export function removeSheetRoute(root: string): void {
  const paths = nextSheetPaths(root);
  if (!paths) return;
  const stubs = [paths.page, join(dirname(paths.page), LEGACY_SHEET_PAGE_NAME)];
  if (!stubs.some(isGeneratedStub)) return;
  rmSync(paths.routeFolder, { recursive: true, force: true });
}

function isGeneratedStub(file: string): boolean {
  try {
    return readFileSync(file, "utf8").includes(STUB_MARKER);
  } catch {
    return false;
  }
}

function packageName(specifier: string): string {
  const parts = specifier.split("/");
  return specifier.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0] ?? specifier;
}

/** A package the project can resolve; a missing one would fail the whole sheet module's compile, not one cell. */
function packageInstalled(root: string, specifier: string): boolean {
  let directory = root;
  for (;;) {
    if (existsSync(join(directory, "node_modules", packageName(specifier), "package.json"))) return true;
    const parent = dirname(directory);
    if (parent === directory) return false;
    directory = parent;
  }
}

const SOURCE_FILE = /\.[cm]?[jt]sx?$/;
/** App Router and Pages Router files Next renders itself; they are routes, never cells. */
const APP_ROUTE_FILE = /(?:^|\/)(?:layout|page|template|default|loading|error|global-error|not-found|forbidden|unauthorized|route)\.[cm]?[jt]sx?$/;
const PAGES_ROUTE_FILE = /^(?:src\/)?pages\//;

export interface NextSheetDefinitionInput {
  framework: ComponentFrameworkAdapter;
  root: string;
  definition: string;
  contracts: readonly ComponentContract[];
  /** Configured wrapper path, else the adapter's conventional names. */
  wrapper?: string;
}

/**
 * The module behind `.nudge/next/component-sheet.ts`. Unlike Vite, an unresolvable `import()` fails the whole
 * compile, so it lists only modules that exist and that a browser can load.
 */
export function serializeNextSheetDefinition(input: NextSheetDefinitionInput): string {
  const files = new Map<string, string | null>();
  const browserModule = (contract: ComponentContract): string | null => {
    if (files.has(contract.file)) return files.get(contract.file)!;
    let specifier: string | null = null;
    if (APP_ROUTE_FILE.test(contract.file) || PAGES_ROUTE_FILE.test(contract.file)) {
      specifier = null;
    } else if (SOURCE_FILE.test(contract.file)) {
      const file = resolve(input.root, contract.file);
      try {
        const source = readFileSync(file, "utf8");
        if (!input.framework.isServerOnlyModule?.(source)) specifier = relativeSpecifier(input.definition, file);
      } catch {
        // a contract whose file is gone renders nothing
      }
    } else if (packageInstalled(input.root, contract.file)) {
      specifier = contract.file;
    }
    files.set(contract.file, specifier);
    return specifier;
  };
  const contracts = input.contracts.filter((contract) => browserModule(contract) !== null);
  const wrapper = findSheetWrapperFile(input.framework, input.root, input.wrapper, (file) => existsSync(file));
  return [
    `// ${STUB_MARKER}; rewritten when component contracts change.`,
    // Loaders read either a named or a default export, so a strict project check would reject the module it never wrote.
    "// @ts-nocheck",
    "export const componentSheet = {",
    ...serializeSheetDefinition({
      contracts,
      componentSpecifier: (contract) => browserModule(contract)!,
      wrapperSpecifier: wrapper ? relativeSpecifier(input.definition, wrapper) : null,
      wrapperPath: wrapper ? relative(input.root, wrapper).split(sep).join(posix.sep) : suggestedSheetWrapperFile(input.framework),
    }),
    "};",
    "",
  ].join("\n");
}

/** Rewrites the definition only when its source changes, so an unchanged contract set triggers no HMR update. */
export function writeSheetDefinition(input: NextSheetDefinitionInput): boolean {
  return writeIfChanged(input.definition, serializeNextSheetDefinition(input));
}
